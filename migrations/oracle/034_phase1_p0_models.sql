-- Oracle port of 034_phase1_p0_models.sql.
-- ticket_open_rules.open_time uses VARCHAR2(8) because Oracle has no standalone
-- clock value datatype;
-- values are expected to be formatted as HH24:MI:SS.
DECLARE
    v_exists NUMBER;

    PROCEDURE create_table_if_missing(p_table_name VARCHAR2, p_ddl VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO v_exists
          FROM user_tables
         WHERE table_name = UPPER(p_table_name);
        IF v_exists = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
        END IF;
    END;
BEGIN
    create_table_if_missing('TEAM_EVENTS', q'[
        CREATE TABLE TEAM_EVENTS (
            ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            EVENT_SCOPE VARCHAR2(10) DEFAULT 'team' NOT NULL,
            TEAM_ID VARCHAR2(10),
            GAME_ID VARCHAR2(20),
            STADIUM_ID VARCHAR2(10),
            TITLE VARCHAR2(300) NOT NULL,
            DESCRIPTION CLOB,
            EVENT_TYPE VARCHAR2(30),
            EVENT_START_AT TIMESTAMP,
            EVENT_END_AT TIMESTAMP,
            APPLY_START_AT TIMESTAMP,
            APPLY_END_AT TIMESTAMP,
            LOCATION_TEXT VARCHAR2(200),
            TARGET_AUDIENCE VARCHAR2(200),
            BENEFIT_TEXT VARCHAR2(500),
            IMAGE_URL VARCHAR2(500),
            SOURCE_ID NUMBER(10),
            SOURCE_URL VARCHAR2(500),
            PUBLISHED_AT TIMESTAMP,
            LAST_SEEN_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            STATUS VARCHAR2(20) DEFAULT 'unknown' NOT NULL,
            CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT PK_TEAM_EVENTS PRIMARY KEY (ID),
            CONSTRAINT FK_TEAM_EVENTS_GAME FOREIGN KEY (GAME_ID)
                REFERENCES GAME (GAME_ID) ON DELETE SET NULL,
            CONSTRAINT FK_TEAM_EVENTS_SOURCE FOREIGN KEY (SOURCE_ID)
                REFERENCES DATA_SOURCES (ID) ON DELETE SET NULL
        )
    ]');

    create_table_if_missing('ROSTER_TRANSACTIONS', q'[
        CREATE TABLE ROSTER_TRANSACTIONS (
            ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            TRANSACTION_DATE DATE NOT NULL,
            TEAM_ID VARCHAR2(10) NOT NULL,
            PLAYER_ID NUMBER(10),
            PLAYER_NAME VARCHAR2(100) NOT NULL,
            ACTION VARCHAR2(20) NOT NULL,
            ROSTER_LEVEL VARCHAR2(20) DEFAULT 'first_team' NOT NULL,
            INFERRED_TO_LEVEL VARCHAR2(20),
            SOURCE_TYPE VARCHAR2(30) DEFAULT 'kbo_today_page' NOT NULL,
            SOURCE_ID NUMBER(10),
            BEFORE_SNAPSHOT_ID NUMBER(10),
            AFTER_SNAPSHOT_ID NUMBER(10),
            CONFIDENCE VARCHAR2(10) DEFAULT 'high' NOT NULL,
            DEDUPE_KEY VARCHAR2(100) NOT NULL,
            CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT PK_ROSTER_TRANSACTIONS PRIMARY KEY (ID),
            CONSTRAINT FK_ROSTER_TRANS_PLAYER FOREIGN KEY (PLAYER_ID)
                REFERENCES PLAYER_BASIC (PLAYER_ID),
            CONSTRAINT FK_ROSTER_TRANS_SOURCE FOREIGN KEY (SOURCE_ID)
                REFERENCES DATA_SOURCES (ID) ON DELETE SET NULL,
            CONSTRAINT FK_ROSTER_TRANS_BEFORE FOREIGN KEY (BEFORE_SNAPSHOT_ID)
                REFERENCES RAW_SOURCE_SNAPSHOTS (ID) ON DELETE SET NULL,
            CONSTRAINT FK_ROSTER_TRANS_AFTER FOREIGN KEY (AFTER_SNAPSHOT_ID)
                REFERENCES RAW_SOURCE_SNAPSHOTS (ID) ON DELETE SET NULL,
            CONSTRAINT UQ_ROSTER_TRANS_DEDUPE UNIQUE (DEDUPE_KEY)
        )
    ]');

    create_table_if_missing('TICKET_PRICES', q'[
        CREATE TABLE TICKET_PRICES (
            ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            TEAM_ID VARCHAR2(10) NOT NULL,
            STADIUM_ID VARCHAR2(10) NOT NULL,
            SEASON NUMBER(10) NOT NULL,
            SEAT_GRADE VARCHAR2(50) NOT NULL,
            DAY_TYPE VARCHAR2(20) DEFAULT 'weekday' NOT NULL,
            AUDIENCE_TYPE VARCHAR2(30),
            PRICE NUMBER(10) NOT NULL,
            CURRENCY VARCHAR2(10) DEFAULT 'KRW' NOT NULL,
            SOURCE_ID NUMBER(10),
            SOURCE_URL VARCHAR2(500),
            EFFECTIVE_FROM DATE,
            EFFECTIVE_TO DATE,
            CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT PK_TICKET_PRICES PRIMARY KEY (ID),
            CONSTRAINT FK_TICKET_PRICES_SOURCE FOREIGN KEY (SOURCE_ID)
                REFERENCES DATA_SOURCES (ID) ON DELETE SET NULL,
            CONSTRAINT UQ_TICKET_PRICES_KEY
                UNIQUE (TEAM_ID, SEASON, SEAT_GRADE, DAY_TYPE, AUDIENCE_TYPE)
        )
    ]');

    create_table_if_missing('TICKET_OPEN_RULES', q'[
        CREATE TABLE TICKET_OPEN_RULES (
            ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            TEAM_ID VARCHAR2(10) NOT NULL,
            PLATFORM VARCHAR2(50) NOT NULL,
            OPEN_OFFSET_DAYS NUMBER(10) NOT NULL,
            OPEN_TIME VARCHAR2(8) NOT NULL,
            SALES_CLOSE_RULE CLOB,
            MAX_TICKETS_PER_USER NUMBER(10),
            FEE_RULE CLOB,
            CANCEL_RULE CLOB,
            SOURCE_ID NUMBER(10),
            NOTE VARCHAR2(500),
            CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT PK_TICKET_OPEN_RULES PRIMARY KEY (ID),
            CONSTRAINT FK_TICKET_OPEN_SOURCE FOREIGN KEY (SOURCE_ID)
                REFERENCES DATA_SOURCES (ID) ON DELETE SET NULL,
            CONSTRAINT UQ_TICKET_OPEN_RULE_KEY
                UNIQUE (TEAM_ID, PLATFORM, OPEN_OFFSET_DAYS, OPEN_TIME)
        )
    ]');
END;
