DECLARE
    v_exists NUMBER;

    PROCEDURE create_index_if_missing(p_index_name VARCHAR2, p_ddl VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO v_exists
          FROM user_indexes
         WHERE index_name = UPPER(p_index_name);
        IF v_exists = 0 THEN
            BEGIN
                EXECUTE IMMEDIATE p_ddl;
            EXCEPTION
                WHEN OTHERS THEN
                    IF SQLCODE != -1408 THEN
                        RAISE;
                    END IF;
            END;
        END IF;
    END;
BEGIN
    create_index_if_missing('IDX_TEAM_EVENT_SCOPE',
        'CREATE INDEX IDX_TEAM_EVENT_SCOPE ON TEAM_EVENTS (EVENT_SCOPE)');
    create_index_if_missing('IDX_TEAM_EVENT_TEAM',
        'CREATE INDEX IDX_TEAM_EVENT_TEAM ON TEAM_EVENTS (TEAM_ID)');
    create_index_if_missing('IDX_TEAM_EVENT_GAME',
        'CREATE INDEX IDX_TEAM_EVENT_GAME ON TEAM_EVENTS (GAME_ID)');
    create_index_if_missing('IDX_TEAM_EVENT_TYPE',
        'CREATE INDEX IDX_TEAM_EVENT_TYPE ON TEAM_EVENTS (EVENT_TYPE)');
    create_index_if_missing('IDX_TEAM_EVENT_STATUS',
        'CREATE INDEX IDX_TEAM_EVENT_STATUS ON TEAM_EVENTS (STATUS)');
    create_index_if_missing('IDX_TEAM_EVENT_PUBLISHED',
        'CREATE INDEX IDX_TEAM_EVENT_PUBLISHED ON TEAM_EVENTS (PUBLISHED_AT)');
    create_index_if_missing('IDX_RT_DATE',
        'CREATE INDEX IDX_RT_DATE ON ROSTER_TRANSACTIONS (TRANSACTION_DATE)');
    create_index_if_missing('IDX_RT_TEAM',
        'CREATE INDEX IDX_RT_TEAM ON ROSTER_TRANSACTIONS (TEAM_ID)');
    create_index_if_missing('IDX_RT_DATE_TEAM',
        'CREATE INDEX IDX_RT_DATE_TEAM ON ROSTER_TRANSACTIONS (TRANSACTION_DATE, TEAM_ID)');
    create_index_if_missing('IDX_RT_ACTION',
        'CREATE INDEX IDX_RT_ACTION ON ROSTER_TRANSACTIONS (ACTION)');
    create_index_if_missing('IDX_RT_PLAYER',
        'CREATE INDEX IDX_RT_PLAYER ON ROSTER_TRANSACTIONS (PLAYER_ID)');
    create_index_if_missing('IDX_TP_TEAM',
        'CREATE INDEX IDX_TP_TEAM ON TICKET_PRICES (TEAM_ID)');
    create_index_if_missing('IDX_TP_STADIUM',
        'CREATE INDEX IDX_TP_STADIUM ON TICKET_PRICES (STADIUM_ID)');
    create_index_if_missing('IDX_TP_SEASON',
        'CREATE INDEX IDX_TP_SEASON ON TICKET_PRICES (SEASON)');
    create_index_if_missing('IDX_TOR_TEAM',
        'CREATE INDEX IDX_TOR_TEAM ON TICKET_OPEN_RULES (TEAM_ID)');
    create_index_if_missing('IDX_TOR_PLATFORM',
        'CREATE INDEX IDX_TOR_PLATFORM ON TICKET_OPEN_RULES (PLATFORM)');
END;
