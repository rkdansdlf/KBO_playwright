-- Oracle port of 039_stadium_realtime_tables.sql.
-- Payload documents are stored as CLOB and flags as NUMBER(1).
DECLARE
    v_exists NUMBER;

    PROCEDURE create_table_if_missing(p_table_name VARCHAR2, p_ddl VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO v_exists
          FROM user_tables
         WHERE table_name = UPPER(p_table_name);
        IF v_exists = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
        END IF;
    END;
BEGIN
    create_table_if_missing('STADIUM_TRANSIT_TIMES', q'[
        CREATE TABLE STADIUM_TRANSIT_TIMES (
            ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            STADIUM_CODE VARCHAR2(10) NOT NULL,
            ORIGIN_LABEL VARCHAR2(100) NOT NULL,
            ORIGIN_LAT NUMBER,
            ORIGIN_LNG NUMBER,
            TRANSPORT_MODE VARCHAR2(20) NOT NULL,
            MEASURED_AT TIMESTAMP NOT NULL,
            GAME_DATE DATE NOT NULL,
            DURATION_MINUTES NUMBER(10) NOT NULL,
            DISTANCE_METERS NUMBER(10),
            CONGESTION_FACTOR NUMBER,
            SOURCE_API VARCHAR2(30) NOT NULL,
            RAW_RESPONSE CLOB,
            CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT PK_STADIUM_TRANSIT_TIMES PRIMARY KEY (ID),
            CONSTRAINT FK_STT_STADIUM FOREIGN KEY (STADIUM_CODE)
                REFERENCES STADIUM_INFO (STADIUM_CODE) ON DELETE CASCADE,
            CONSTRAINT UQ_STT_MEASUREMENT
                UNIQUE (STADIUM_CODE, ORIGIN_LABEL, TRANSPORT_MODE, MEASURED_AT)
        )
    ]');

    create_table_if_missing('STADIUM_CONGESTION', q'[
        CREATE TABLE STADIUM_CONGESTION (
            ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            STADIUM_CODE VARCHAR2(10) NOT NULL,
            LOCATION_TYPE VARCHAR2(30) NOT NULL,
            LOCATION_LABEL VARCHAR2(100) NOT NULL,
            MEASURED_AT TIMESTAMP NOT NULL,
            GAME_DATE DATE NOT NULL,
            CONGESTION_LEVEL VARCHAR2(20) NOT NULL,
            CONGESTION_INDEX NUMBER,
            PEOPLE_COUNT NUMBER(10),
            SOURCE VARCHAR2(50) NOT NULL,
            RAW_DATA CLOB,
            CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT PK_STADIUM_CONGESTION PRIMARY KEY (ID),
            CONSTRAINT FK_SC_STADIUM FOREIGN KEY (STADIUM_CODE)
                REFERENCES STADIUM_INFO (STADIUM_CODE) ON DELETE CASCADE,
            CONSTRAINT UQ_SC_MEASUREMENT
                UNIQUE (STADIUM_CODE, LOCATION_LABEL, MEASURED_AT)
        )
    ]');

    create_table_if_missing('STADIUM_OPERATION_NOTICES', q'[
        CREATE TABLE STADIUM_OPERATION_NOTICES (
            ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            STADIUM_CODE VARCHAR2(10) NOT NULL,
            NOTICE_TYPE VARCHAR2(30) NOT NULL,
            TITLE VARCHAR2(500) NOT NULL,
            CONTENT CLOB,
            PUBLISHED_AT TIMESTAMP,
            GAME_DATE DATE,
            SOURCE_NAME VARCHAR2(100) NOT NULL,
            SOURCE_URL VARCHAR2(500),
            EXTERNAL_ID VARCHAR2(200),
            IS_URGENT NUMBER(1) DEFAULT 0 NOT NULL,
            IS_CONFIRMED NUMBER(1) DEFAULT 1 NOT NULL,
            RAW_SNAPSHOT CLOB,
            CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT PK_STADIUM_OP_NOTICES PRIMARY KEY (ID),
            CONSTRAINT FK_SON_STADIUM FOREIGN KEY (STADIUM_CODE)
                REFERENCES STADIUM_INFO (STADIUM_CODE) ON DELETE CASCADE,
            CONSTRAINT UQ_SON_EXTERNAL
                UNIQUE (STADIUM_CODE, SOURCE_NAME, EXTERNAL_ID),
            CONSTRAINT UQ_SON_CONTENT
                UNIQUE (STADIUM_CODE, SOURCE_NAME, TITLE, PUBLISHED_AT)
        )
    ]');
END;
