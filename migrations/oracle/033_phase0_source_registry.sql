DECLARE
    v_exists NUMBER;

    PROCEDURE create_table_if_missing(p_table_name VARCHAR2, p_ddl VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO v_exists
          FROM user_tables
         WHERE table_name = UPPER(p_table_name);
        IF v_exists = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
        END IF;
    END;
BEGIN
    create_table_if_missing('DATA_SOURCES', q'[
        CREATE TABLE DATA_SOURCES (
            ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            SOURCE_KEY VARCHAR2(100) NOT NULL,
            SOURCE_TYPE VARCHAR2(30) NOT NULL,
            TEAM_ID VARCHAR2(10),
            STADIUM_ID VARCHAR2(10),
            TARGET_DOMAIN VARCHAR2(30) NOT NULL,
            RELIABILITY VARCHAR2(10) DEFAULT 'medium' NOT NULL,
            PARSER_NAME VARCHAR2(100),
            CRAWL_FREQUENCY VARCHAR2(30),
            BASE_URL VARCHAR2(500),
            LAST_SUCCESS_AT TIMESTAMP,
            LAST_CONTENT_HASH VARCHAR2(64),
            IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
            CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT PK_DATA_SOURCES PRIMARY KEY (ID),
            CONSTRAINT UQ_DATA_SOURCES_SOURCE_KEY UNIQUE (SOURCE_KEY)
        )
    ]');

    create_table_if_missing('RAW_SOURCE_SNAPSHOTS', q'[
        CREATE TABLE RAW_SOURCE_SNAPSHOTS (
            ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
            DATA_SOURCE_ID NUMBER(10) NOT NULL,
            FETCHED_AT TIMESTAMP NOT NULL,
            CONTENT_HASH VARCHAR2(64),
            RAW_HTML_OR_JSON_PATH VARCHAR2(500),
            STATUS_CODE NUMBER(10),
            PARSE_STATUS VARCHAR2(20) DEFAULT 'pending' NOT NULL,
            PARSER_VERSION VARCHAR2(30),
            REPROCESS_STATUS VARCHAR2(20),
            ERROR_MESSAGE CLOB,
            CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
            CONSTRAINT PK_RAW_SOURCE_SNAPSHOTS PRIMARY KEY (ID),
            CONSTRAINT FK_RAW_SNAPSHOTS_SOURCE FOREIGN KEY (DATA_SOURCE_ID)
                REFERENCES DATA_SOURCES (ID) ON DELETE CASCADE,
            CONSTRAINT UQ_RAW_SNAPSHOTS_KEY UNIQUE (DATA_SOURCE_ID, CONTENT_HASH)
        )
    ]');
END;
/

DECLARE
    v_exists NUMBER;

    PROCEDURE create_index_if_missing(p_index_name VARCHAR2, p_ddl VARCHAR2) IS
    BEGIN
        SELECT COUNT(*) INTO v_exists
          FROM user_indexes
         WHERE index_name = UPPER(p_index_name);
        IF v_exists = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
        END IF;
    END;
BEGIN
    create_index_if_missing('IDX_DS_TARGET_DOMAIN',
        'CREATE INDEX IDX_DS_TARGET_DOMAIN ON DATA_SOURCES (TARGET_DOMAIN)');
